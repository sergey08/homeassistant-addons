"""Restore encrypted LiveSync snapshots ONLY to an empty disposable CouchDB.

This is NOT a revision-preserving CouchDB backup restore. It creates NEW revs
and never issues an update, overwrites a document, deletes, or retries. No
transport is constructed: injected callbacks are exclusively test-only.
"""
from copy import deepcopy

from livesync_isolated_backup_store import read_signed_backup
from livesync_multichunk_audit import assemble_encrypted_chunks
from livesync_revision_contract import require_confirmed_create_response
from livesync_write_preflight import UnsafeWrite


class DisposableRestoreError(ValueError):
    def __init__(self, phase):
        self.phase = phase
        super().__init__("disposable_restore_incomplete")


def restore_to_empty_disposable_database(backup_root, backup_id, backup_key,
                                         list_document_ids, read_document,
                                         put_document, passphrase, salt_b64, *,
                                         isolated_test=False,
                                         disposable_database=False,
                                         remote_writes_enabled=False):
    """Create encrypted leaves, verify each, then create encrypted parent last.

    Authenticate the persisted backup before accessing the target database.
    Target must be an entirely empty throwaway database. Original revision
    strings are only historical evidence in the snapshot; the new CouchDB
    revisions are generated by target server. Never use on real LiveSync DB.
    """
    if (isolated_test is not True or disposable_database is not True
            or remote_writes_enabled is not False):
        raise UnsafeWrite("disposable_restore_only")
    if not all(callable(x) for x in (list_document_ids, read_document, put_document)):
        raise UnsafeWrite("disposable_transport_required")
    record = read_signed_backup(backup_root, backup_id, backup_key,
                                isolated_test=isolated_test,
                                remote_writes_enabled=remote_writes_enabled)
    snapshot = record["backup"]["snapshot"]
    if not isinstance(snapshot, dict):
        raise UnsafeWrite("invalid_snapshot")
    parent = snapshot.get("parent")
    leaves = snapshot.get("leaves")
    if (not isinstance(parent, dict) or not isinstance(leaves, list)
            or not 1 <= len(leaves) <= 512):
        raise UnsafeWrite("invalid_snapshot_documents")
    ids = [leaf.get("_id") if isinstance(leaf, dict) else None for leaf in leaves]
    if (any(not isinstance(ident, str) or not ident.startswith("h:+") for ident in ids)
            or len(set(ids)) != len(ids) or parent.get("_id") in ids):
        raise UnsafeWrite("invalid_leaf_identities")
    leaf_map = {leaf["_id"]: leaf for leaf in leaves}
    try:
        checked = assemble_encrypted_chunks(
            parent, leaf_map, snapshot["path"], snapshot["parent_revision"],
            passphrase, salt_b64)
    except Exception as exc:
        raise UnsafeWrite("backup_ciphertext_not_verified") from exc
    # Assembly verifies every unique child reference, so any surplus leaf is unreferenced.
    if checked["chunks"] != len(leaf_map):
        raise UnsafeWrite("unexpected_backup_leaves")
    if parent.get("_attachments") is not None:
        raise UnsafeWrite("unsupported_backup_parent_attachments")
    if parent.get("_conflicts") or parent.get("_deleted") or parent.get("deleted"):
        raise UnsafeWrite("conflicted_backup_parent")
    if any(leaf.get("_attachments") is not None
           or leaf.get("_conflicts") or leaf.get("_deleted")
           or leaf.get("deleted") for leaf in leaves):
        raise UnsafeWrite("unsupported_backup_leaf")

    try:
        if list_document_ids() != []:
            raise UnsafeWrite("target_database_not_empty")
        # Explicitly recheck every expected ID before the first operation.
        for ident in ids + [parent["_id"]]:
            if read_document(ident) is not None:
                raise UnsafeWrite("target_document_exists")
    except UnsafeWrite:
        raise
    except Exception as exc:
        raise DisposableRestoreError("target_preflight_uncertain") from exc

    confirmed_leaves = {}
    for leaf in leaves:
        candidate = deepcopy(leaf)
        candidate.pop("_rev", None)
        try:
            status, response = put_document(deepcopy(candidate))
            new_revision = require_confirmed_create_response(
                status, response, candidate["_id"])
            fetched = read_document(candidate["_id"])
            if (not isinstance(fetched, dict)
                    or fetched.get("_rev") != new_revision
                    or {k: v for k, v in fetched.items() if k != "_rev"} != candidate):
                raise ValueError("leaf_readback_unverified")
            confirmed_leaves[candidate["_id"]] = {**candidate, "_rev": new_revision}
        except Exception as exc:
            raise DisposableRestoreError("leaf_uncertain") from exc

    candidate = deepcopy(parent)
    candidate.pop("_rev", None)
    try:
        status, response = put_document(deepcopy(candidate))
        new_revision = require_confirmed_create_response(
            status, response, candidate["_id"])
        fetched = read_document(candidate["_id"])
        if (not isinstance(fetched, dict) or fetched.get("_rev") != new_revision
                or {k: v for k, v in fetched.items() if k != "_rev"} != candidate):
            raise ValueError("parent_readback_unverified")
        # Check the exact ciphertext and revisions again after creating the parent.
        restored_leaves = {ident: read_document(ident) for ident in ids}
        if restored_leaves != confirmed_leaves:
            raise ValueError("restored_leaf_changed")
        restored = assemble_encrypted_chunks(
            fetched, restored_leaves,
            snapshot["path"], new_revision, passphrase, salt_b64)
        if restored["content"] != checked["content"]:
            raise ValueError("restored_content_mismatch")
    except Exception as exc:
        raise DisposableRestoreError("parent_uncertain") from exc
    return {"status": "restored_in_empty_disposable_database_only",
            "confirmed_leaves": len(confirmed_leaves), "verified_bytes": checked["bytes"],
            "automatic_retry": False, "restore_to_production_enabled": False,
            "remote_writes_enabled": False}
